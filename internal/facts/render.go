package facts

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/luckylucky0001/codewiki/internal/model"
)

// GeneratedMarker is placed in every generated facts page.
const GeneratedMarker = "<!-- GENERATED by kb scan — DO NOT EDIT. Changes are overwritten on every compound. -->"

func mustJSON(v any) []byte {
	b, _ := json.MarshalIndent(v, "", "  ")
	return append(b, '\n')
}

// RoutesJSON renders routes.json (interchange schema v1).
func RoutesJSON(f *model.Facts) []byte {
	return mustJSON(struct {
		Version int           `json:"version"`
		Routes  []model.Route `json:"routes"`
	}{1, f.Routes})
}

// TestIDsJSON renders testids.json (interchange schema v1).
func TestIDsJSON(f *model.Facts) []byte {
	return mustJSON(struct {
		Version int            `json:"version"`
		TestIDs []model.TestID `json:"testids"`
	}{1, f.TestIDs})
}

// APIsJSON renders apis.json (interchange schema v1).
func APIsJSON(f *model.Facts) []byte {
	return mustJSON(struct {
		Version int         `json:"version"`
		APIs    []model.API `json:"apis"`
	}{1, f.APIs})
}

// RequirementsJSON renders requirements.json.
func RequirementsJSON(reqs []model.Requirement) []byte {
	if reqs == nil {
		reqs = []model.Requirement{}
	}
	return mustJSON(struct {
		Version      int                 `json:"version"`
		Requirements []model.Requirement `json:"requirements"`
	}{1, reqs})
}

func header(id, title string) string {
	return fmt.Sprintf("---\nid: %s\ntitle: %s\nkind: facts\ngenerated: true\n---\n%s\n\n# %s\n\n", id, title, GeneratedMarker, title)
}

func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// Render returns all generated facts files keyed by wiki-relative path.
// platforms is the configured platform list (pages exist even when empty).
func Render(f *model.Facts, g *model.Graph, platforms []string) map[string][]byte {
	out := map[string][]byte{
		"facts/routes.json":  RoutesJSON(f),
		"facts/testids.json": TestIDsJSON(f),
		"facts/apis.json":    APIsJSON(f),
	}
	for _, p := range platforms {
		var b strings.Builder
		// routes
		b.WriteString(header("facts/"+p+"/routes", strings.Title(p)+" routes"))
		if sc := f.Schemes[p]; len(sc) > 0 {
			fmt.Fprintf(&b, "Deep-link schemes: %s\n\n", "`"+strings.Join(sc, "`, `")+"`")
		}
		b.WriteString("| route_id | pattern | deeplink | symbol |\n|---|---|---|---|\n")
		for _, r := range f.Routes {
			if r.Platform == p {
				fmt.Fprintf(&b, "| `%s` | `%s` | `%s` | `%s` |\n", r.RouteID, esc(r.Pattern), esc(r.Deeplink), r.Symbol)
			}
		}
		var warns []string
		for _, w := range f.Warnings {
			warns = append(warns, "- ⚠ "+w)
		}
		if len(warns) > 0 {
			b.WriteString("\n## Extractor warnings\n\n" + strings.Join(warns, "\n") + "\n")
		}
		var entries []string
		for _, e := range f.Entries {
			if e.Platform == p {
				entries = append(entries, fmt.Sprintf("- %s `%s` (`%s`)", e.Kind, e.Name, e.File))
			}
		}
		if len(entries) > 0 {
			b.WriteString("\n## Entry points\n\n" + strings.Join(entries, "\n") + "\n")
		}
		out["facts/"+p+"/routes.md"] = []byte(b.String())

		b.Reset()
		b.WriteString(header("facts/"+p+"/testids", strings.Title(p)+" testIDs"))
		b.WriteString("Dynamic IDs are recorded by their literal prefix (e.g. `product_item_`).\n\n| tid | route_id | location |\n|---|---|---|\n")
		for _, t := range f.TestIDs {
			if t.Platform == p {
				fmt.Fprintf(&b, "| `%s` | `%s` | `%s:%d` |\n", t.Tid, t.RouteID, t.File, t.Line)
			}
		}
		out["facts/"+p+"/testids.md"] = []byte(b.String())

		b.Reset()
		b.WriteString(header("facts/"+p+"/apis", strings.Title(p)+" HTTP APIs"))
		b.WriteString("| method | path | symbol |\n|---|---|---|\n")
		for _, a := range f.APIs {
			if a.Platform == p {
				fmt.Fprintf(&b, "| %s | `%s` | `%s` |\n", a.Method, esc(a.Path), a.Symbol)
			}
		}
		out["facts/"+p+"/apis.md"] = []byte(b.String())

		b.Reset()
		b.WriteString(header("facts/"+p+"/symbols", strings.Title(p)+" symbol map"))
		b.WriteString("Top-level symbols per file (repo-map style). Use `kb anchor <id>` for the current hash.\n\n")
		byFile := map[string][]*model.Symbol{}
		var files []string
		for _, s := range g.Symbols {
			if s.Platform != p || s.Parent != "" {
				continue
			}
			if _, ok := byFile[s.File]; !ok {
				files = append(files, s.File)
			}
			byFile[s.File] = append(byFile[s.File], s)
		}
		sort.Strings(files)
		for _, file := range files {
			fmt.Fprintf(&b, "### `%s`\n\n", file)
			for _, s := range byFile[file] {
				fmt.Fprintf(&b, "- %s `%s` — `%s`\n", s.Kind, s.Qual, esc(s.Signature))
			}
			b.WriteString("\n")
		}
		var fails []string
		for _, pf := range g.ParseFailures {
			if fi, ok := g.Files[pf.File]; ok && fi.Platform == p {
				fails = append(fails, fmt.Sprintf("- `%s:%d` %s", pf.File, pf.Line, pf.Error))
			}
		}
		if len(fails) > 0 {
			b.WriteString("## parse_failures\n\n" + strings.Join(fails, "\n") + "\n")
		}
		out["facts/"+p+"/symbols.md"] = []byte(b.String())
	}
	return out
}
