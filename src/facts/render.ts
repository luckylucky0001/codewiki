// Render generated facts files (JSON interchange schema v1 + per-platform markdown).
import type { Facts, Graph, Requirement, Symbol } from '../model.js';
import { cmpStr, goJSON } from '../util/go.js';

export const GeneratedMarker = '<!-- GENERATED by kb scan — DO NOT EDIT. Changes are overwritten on every compound. -->';

export const mustJSON = (v: unknown): string => goJSON(v, '  ') + '\n';

export function routesJSON(f: Facts): string {
  return mustJSON({ version: 1, routes: f.routes });
}
export function testIDsJSON(f: Facts): string {
  return mustJSON({ version: 1, testids: f.testids });
}
export function apisJSON(f: Facts): string {
  return mustJSON({ version: 1, apis: f.apis });
}

export function requirementJSON(r: Requirement): Record<string, unknown> {
  const o: Record<string, unknown> = { id: r.id, source: r.source };
  if (r.line) o.line = r.line;
  o.text = r.text;
  o.status = r.status;
  o.anchors = r.anchors;
  o.route_ids = r.route_ids;
  if (r.evidence && r.evidence.length) o.evidence = r.evidence;
  return o;
}

export function requirementsJSON(reqs: Requirement[] | null): string {
  return mustJSON({ version: 1, requirements: (reqs ?? []).map(requirementJSON) });
}

/** Facts as Go would marshal model.Facts (omitempty on extras). */
export function factsJSON(f: Facts): Record<string, unknown> {
  const o: Record<string, unknown> = { routes: f.routes, testids: f.testids, apis: f.apis };
  if (f.schemes && Object.keys(f.schemes).length) {
    const s: Record<string, string[]> = {};
    for (const k of Object.keys(f.schemes).sort(cmpStr)) s[k] = f.schemes[k]!;
    o.schemes = s;
  }
  if (f.entries?.length) o.entries = f.entries;
  if (f.warnings?.length) o.warnings = f.warnings;
  if (f.navigation?.length) o.navigation = f.navigation;
  return o;
}

function header(id: string, title: string): string {
  return `---\nid: ${id}\ntitle: ${title}\nkind: facts\ngenerated: true\n---\n${GeneratedMarker}\n\n# ${title}\n\n`;
}

const esc = (s: string) => s.replaceAll('|', '\\|');
const title = (s: string) => s.replace(/(^|[^\p{L}\p{N}_'])(\p{L})/gu, (_, a: string, b: string) => a + b.toUpperCase());

/** All generated facts files keyed by wiki-relative path. */
export function renderFacts(f: Facts, g: Graph, platforms: string[]): Map<string, string> {
  const out = new Map<string, string>([
    ['facts/routes.json', routesJSON(f)],
    ['facts/testids.json', testIDsJSON(f)],
    ['facts/apis.json', apisJSON(f)],
  ]);
  for (const p of platforms) {
    let b = header('facts/' + p + '/routes', title(p) + ' routes');
    const sc = f.schemes?.[p];
    if (sc && sc.length) b += `Deep-link schemes: ${'`' + sc.join('`, `') + '`'}\n\n`;
    b += '| route_id | pattern | deeplink | symbol |\n|---|---|---|---|\n';
    for (const r of f.routes ?? []) if (r.platform === p) b += `| \`${r.route_id}\` | \`${esc(r.pattern)}\` | \`${esc(r.deeplink)}\` | \`${r.symbol}\` |\n`;
    const warns = (f.warnings ?? []).map((w) => '- ⚠ ' + w);
    if (warns.length) b += '\n## Extractor warnings\n\n' + warns.join('\n') + '\n';
    const entries = (f.entries ?? []).filter((e) => e.platform === p).map((e) => `- ${e.kind} \`${e.name}\` (\`${e.file}\`)`);
    if (entries.length) b += '\n## Entry points\n\n' + entries.join('\n') + '\n';
    const edges = (f.navigation ?? []).filter((e) => e.platform === p).map((e) => `| \`${e.from}\` | \`${e.to}\` | ${e.kind} | \`${e.file}\` L${e.line} |`);
    if (edges.length) b += '\n## Navigation edges\n\n| from | to | kind | source |\n|---|---|---|---|\n' + edges.join('\n') + '\n';
    out.set('facts/' + p + '/routes.md', b);

    b = header('facts/' + p + '/testids', title(p) + ' testIDs');
    b += 'Dynamic IDs are recorded by their literal prefix (e.g. `product_item_`).\n\n| tid | route_id | location |\n|---|---|---|\n';
    for (const t of f.testids ?? []) if (t.platform === p) b += `| \`${t.tid}\` | \`${t.route_id}\` | \`${t.file}:${t.line}\` |\n`;
    out.set('facts/' + p + '/testids.md', b);

    b = header('facts/' + p + '/apis', title(p) + ' HTTP APIs');
    b += '| method | path | symbol |\n|---|---|---|\n';
    for (const a of f.apis ?? []) if (a.platform === p) b += `| ${a.method} | \`${esc(a.path)}\` | \`${a.symbol}\` |\n`;
    out.set('facts/' + p + '/apis.md', b);

    b = header('facts/' + p + '/symbols', title(p) + ' symbol map');
    b += 'Top-level symbols per file (repo-map style). Use `kb anchor <id>` for the current hash.\n\n';
    const byFile = new Map<string, Symbol[]>();
    for (const s of g.symbols) {
      if (s.platform !== p || s.parent) continue;
      const a = byFile.get(s.file);
      if (a) a.push(s);
      else byFile.set(s.file, [s]);
    }
    for (const file of [...byFile.keys()].sort(cmpStr)) {
      b += `### \`${file}\`\n\n`;
      for (const s of byFile.get(file)!) b += `- ${s.kind} \`${s.qual}\` — \`${esc(s.signature)}\`\n`;
      b += '\n';
    }
    const fails = g.parse_failures.filter((pf) => g.files[pf.file]?.platform === p).map((pf) => `- \`${pf.file}:${pf.line ?? 0}\` ${pf.error}`);
    if (fails.length) b += '## parse_failures\n\n' + fails.join('\n') + '\n';
    out.set('facts/' + p + '/symbols.md', b);
  }
  return out;
}
